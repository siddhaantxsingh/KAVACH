"""Acoustic lexicon expansion: teach the cue lexicon how the ASR actually mis-hears scam phrases.

For every Latin-script cue phrase in assets/cues.json:
  synthesise it (offline Piper TTS, 2 speeds) -> speaker-phone channel at 2 SNRs ->
  the Guardian's streaming ASR -> normalised hypothesis.
A hypothesis that differs from the phrase becomes an *alias* of the same category if
  * it has at least 2 characters per token on average and is not a stop-word string,
  * it never occurs in benign text (synthetic benign calls + UCI ham SMS), and
  * it does not already match the lexicon as the same category.
Aliases are written to cues.json["asr_aliases"][category] (both the Python and Kotlin
lexicons load them as ordinary phrases), so a phone running the small English model
still sees "rbi" in "arbi" and "money laundering" in "money wandering".

Run again after changing the ASR model; Hindi aliases need the Hindi model (on device).
Usage: python models/asr/expand_lexicon_asr.py --models <dir>
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "bench"))
from e2e_audio import recognizer, speakerphone, stream_asr, tts_engine  # noqa: E402
from kavach_core.lexicon import Lexicon  # noqa: E402
from kavach_core.normalize import normalize  # noqa: E402

STOP = {"a", "an", "the", "to", "of", "and", "i", "you", "it", "is", "in", "on", "for", "or", "be", "do", "o", "oh", "uh", "ah", "the the"}
SKIP_CATS = {"safety_advice"}  # never invent safety advice


def benign_corpus() -> str:
    parts = []
    for line in open(ROOT / "data/synth/out/calls_train.jsonl", encoding="utf-8"):
        c = json.loads(line)
        if c["label"] == 0:
            parts.append(" ".join(s["text"] for s in c["segments"]))
    uci = ROOT / "data/public/raw/sms_spam_uci.tsv"
    if uci.exists():
        for line in open(uci, encoding="utf-8", errors="replace"):
            lab, _, text = line.partition("\t")
            if lab == "ham":
                parts.append(text)
    for r in csv.DictReader(open(ROOT / "data/synth/out/sms_synth.csv", encoding="utf-8")):
        if r["label"] == "0":
            parts.append(r["text"])
    return " " + " ".join(normalize(p) for p in parts) + " "


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="/home/claude/models_dl")
    a = ap.parse_args()
    models = Path(a.models)
    tts, rec = tts_engine(models), recognizer(models)
    rng = np.random.default_rng(3)
    path = ROOT / "assets/cues.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    lex = Lexicon(path)
    benign = benign_corpus()
    aliases: dict[str, list[str]] = {}
    tried = 0
    for cat, c in data["categories"].items():
        if cat in SKIP_CATS:
            continue
        for ph in c["phrases"]:
            if not ph.isascii():
                continue
            spoken = " ".join(t.rstrip("*") for t in ph.split() if t != "~")
            if len(spoken) < 3:
                continue
            for speed in (0.9, 1.1):
                audio = tts.generate(spoken, sid=0, speed=speed)
                s = np.asarray(audio.samples, dtype=np.float32)
                pad = np.zeros(int(0.6 * 16000), dtype=np.float32)
                clean = np.concatenate([pad, s, pad, pad])
                for snr in (25.0, 12.0):
                    tried += 1
                    finals, _ = stream_asr(rec, speakerphone(clean, snr, rng))
                    hyp = normalize(" ".join(t for _, t in finals))
                    if not hyp or hyp == normalize(spoken) or hyp in STOP:
                        continue
                    toks = hyp.split()
                    if len(toks) > len(spoken.split()) + 2 or sum(len(t) for t in toks) / len(toks) < 2.0:
                        continue
                    if cat in lex.categories_in(hyp):
                        continue
                    if f" {hyp} " in benign:
                        continue
                    aliases.setdefault(cat, [])
                    if hyp not in aliases[cat]:
                        aliases[cat].append(hyp)
    data["asr_aliases"] = {k: sorted(v) for k, v in sorted(aliases.items())}
    data["asr_aliases_doc"] = ("Generated by models/asr/expand_lexicon_asr.py from TTS -> speaker-phone channel -> "
                               "sherpa-onnx streaming-zipformer-en-20M. Matched like ordinary phrases of the category.")
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    n = sum(len(v) for v in aliases.values())
    print(f"{tried} synthesised utterances -> {n} aliases in {len(aliases)} categories")
    for k, v in data["asr_aliases"].items():
        print(f"  {k}: {v[:12]}{' …' if len(v) > 12 else ''}")


if __name__ == "__main__":
    main()
