def main():
    rows, fails = [], 0
    for theme, pairs in PAIRS.items():
        for name, fg, bg, need in pairs:
            r = ratio(fg, bg)
            ok = r >= need
            fails += need > 1.0 and not ok
            rows.append(f"| {theme} | {name} | `{fg}` on `{bg}` | {r:.2f}:1 | {'pass' if ok else 'FAIL'}{' (decorative)' if need == 1.0 else ''} |")
    out = ["# KAVACH design tokens: contrast check", "",
           "Generated by `tools/contrast_check.py` from the palette in `android/ui/src/main/kotlin/kavach/shared/Ui.kt`.",
           "Target: at least 4.5:1 for normal text (WCAG 2.x AA). Risk is never shown by colour alone: every status has words.", "",
           "| Theme | Pair | Colours | Ratio | Result |", "|---|---|---|---|---|"] + rows + ["", f"Failures: {fails}"]
    Path(__file__).resolve().parents[1].joinpath("docs/design_tokens.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(rows)); print("failures", fails)

if __name__ == "__main__":
    main()
