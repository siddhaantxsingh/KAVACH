"""WCAG 2.x contrast of every KAVACH foreground/background pair (android/shared/.../Ui.kt palette).
python tools/contrast_check.py  -> prints a table and writes docs/design_tokens.md"""
from pathlib import Path

def lum(h):
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)

PAIRS = {
    "dark": [
        ("text on background", "#F4F1E8", "#0B1020", 4.5), ("text on card", "#F4F1E8", "#151D31", 4.5),
        ("secondary text on background", "#ADB6C8", "#0B1020", 4.5), ("secondary text on card", "#ADB6C8", "#151D31", 4.5),
        ("button text on secondary button", "#F4F1E8", "#1C2640", 4.5), ("white on cobalt (primary button)", "#FFFFFF", "#3157D5", 4.5),
        ("gold on background (labels, highlights)", "#D6B36A", "#0B1020", 4.5), ("gold on card", "#D6B36A", "#151D31", 4.5),
        ("text on listening panel", "#F4F1E8", "#22336B", 4.5), ("ink on caution amber", "#1F1300", "#F2B441", 4.5),
        ("white on stop red", "#FFFFFF", "#B91C1C", 4.5), ("success text on card", "#8FD3A6", "#151D31", 4.5),
        ("danger text on secondary button", "#FCA5A5", "#1C2640", 4.5), ("divider vs card (non-text)", "#29344B", "#151D31", 1.0),
    ],
    "light": [
        ("ink on ivory", "#15213B", "#F7F4ED", 4.5), ("ink on white card", "#15213B", "#FFFFFF", 4.5),
        ("secondary text on ivory", "#4B5670", "#F7F4ED", 4.5), ("secondary text on white", "#4B5670", "#FFFFFF", 4.5),
        ("white on cobalt", "#FFFFFF", "#3157D5", 4.5), ("dark gold text on white", "#76551D", "#FFFFFF", 4.5),
        ("dark gold text on ivory", "#76551D", "#F7F4ED", 4.5), ("ink on listening panel", "#15213B", "#E6ECFB", 4.5),
        ("ink on caution panel", "#4A2F00", "#FBE3B0", 4.5), ("white on stop red", "#FFFFFF", "#B91C1C", 4.5),
        ("red text on white", "#B91C1C", "#FFFFFF", 4.5), ("success text on white", "#1F6B3A", "#FFFFFF", 4.5),
        ("caution text on white", "#8A5A00", "#FFFFFF", 4.5),
    ],
    "stop screen": [("white on stop screen", "#FFFFFF", "#991B1B", 4.5), ("white on dark red button", "#FFFFFF", "#7F1D1D", 4.5),
                    ("red on white button", "#991B1B", "#FFFFFF", 4.5)],
}

def main():
    rows, fails = [], 0
    for theme, pairs in PAIRS.items():
        for name, fg, bg, need in pairs:
            r = ratio(fg, bg)
            ok = r >= need
            fails += need > 1.0 and not ok
            rows.append(f"| {theme} | {name} | `{fg}` on `{bg}` | {r:.2f}:1 | {'pass' if ok else 'FAIL'}{' (decorative)' if need == 1.0 else ''} |")
    out = ["# KAVACH design tokens: contrast check", "",
           "Generated by `tools/contrast_check.py` from the palette in `android/shared/src/main/kotlin/kavach/shared/Ui.kt`.",
           "Target: at least 4.5:1 for normal text (WCAG 2.x AA). Risk is never shown by colour alone: every status has words.", "",
           "| Theme | Pair | Colours | Ratio | Result |", "|---|---|---|---|---|"] + rows + ["", f"Failures: {fails}"]
    Path(__file__).resolve().parents[1].joinpath("docs/design_tokens.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(rows)); print("failures", fails)

if __name__ == "__main__":
    main()
